def get_country(code: str) -> Optional[dict]:
    """Return the country record for an ISO alpha-2 code, or None."""
    if not code:
        return None
    return _BY_CODE.get(code.strip().upper())


def is_valid_country(code: str) -> bool:
    return get_country(code) is not None
